'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
process.env.DATA_DIR=path.join(os.tmpdir(),'wyncore-integration-'+process.pid);
process.env.WYNCORE_OWNER_PASSWORD='test-password-with-more-than-12';
process.env.WYNCORE_SESSION_SECRET='test-session-secret-with-more-than-32-characters';
const {createServer,validateOpportunity,STATUSES}=require('./server');
let server,base,cookie;
test('WYNCORE authenticated API end-to-end',async t=>{
 server=createServer();
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 base='http://127.0.0.1:'+server.address().port;
 t.after(async()=>{await new Promise(resolve=>server.close(resolve));await fs.rm(process.env.DATA_DIR,{recursive:true,force:true})});
 const denied=await fetch(base+'/api/dashboard');
 assert.equal(denied.status,401,'private API must reject anonymous requests');
 const login=await fetch(base+'/api/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({password:process.env.WYNCORE_OWNER_PASSWORD})});
 assert.equal(login.status,200,'owner login should succeed');
 cookie=login.headers.get('set-cookie').split(';')[0];
 const dashboard=await fetch(base+'/api/dashboard',{headers:{cookie}});
 assert.equal(dashboard.status,200);
 const created=await fetch(base+'/api/opportunities',{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({title:'Teste de oportunidade',source:'Fonte de teste',value:125,url:'https://example.org/opportunity'})});
 assert.equal(created.status,201);
 const opportunity=await created.json();
 const taskResponse=await fetch(base+'/api/tasks',{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({opportunityId:opportunity.id})});
 assert.equal(taskResponse.status,201);
 const task=await taskResponse.json();
 const changed=await fetch(base+'/api/tasks/'+task.id,{method:'PATCH',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({status:'Recebido'})});
 assert.equal(changed.status,200);
 const report=await fetch(base+'/api/report.csv',{headers:{cookie}});
 assert.equal(report.status,200);
 assert.match(await report.text(),/Teste de oportunidade/);
 const privateFile=await fetch(base+'/server.js');
 assert.equal(privateFile.status,404,'server source must not be served publicly');
 const signupWithoutPhone=await fetch(base+'/api/access-request',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({name:'Sem Telefone',email:'semtelefone@example.org',password:'senha-segura-123'})});
 assert.equal(signupWithoutPhone.status,400,'public signup must require a phone number');
 const signup=await fetch(base+'/api/access-request',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({name:'Participante Teste',email:'participante@example.org',phone:'11987654321',password:'senha-segura-123'})});
 assert.equal(signup.status,201,'participant access request should be created');
 const pendingDash=await (await fetch(base+'/api/dashboard',{headers:{cookie}})).json();
 const participant=pendingDash.participants.find(p=>p.email==='participante@example.org');
 assert.ok(participant,'pending participant should appear for the admin');
 const approval=await fetch(base+'/api/participants/approve',{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({participantId:participant.id,role:'participant'})});
 assert.equal(approval.status,200,'admin should approve participant');
 const participantCreated=await fetch(base+'/api/participants',{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({name:'Participante Direto',phone:'21987654321',password:'senha-inicial-123'})});
 assert.equal(participantCreated.status,201,'admin should be able to add a participant directly');
 const directParticipant=(await participantCreated.json()).participant;
 const directPending=await (await fetch(base+'/api/dashboard',{headers:{cookie}})).json();
 assert.ok(directPending.participants.some(p=>p.id===directParticipant.id));
 const directApproval=await fetch(base+'/api/participants/approve',{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({participantId:directParticipant.id,role:'participant'})});
 assert.equal(directApproval.status,200);
 const directLogin=await fetch(base+'/api/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({identifier:'21987654321',password:'senha-inicial-123'})});
 assert.equal(directLogin.status,200,'new participant should be able to log in by phone after approval');
 const companyLead=await fetch(base+'/api/company/leads',{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({company:'Empresa Exemplo Ltda',contact:'contato@empresa.example',channel:'email',notes:'Contato inicial'})});
 assert.equal(companyLead.status,201,'admin should save a company prospect');
 const lead=await companyLead.json();
 const leadUpdate=await fetch(base+'/api/company/leads/'+lead.id,{method:'PATCH',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({status:'proposal'})});
 assert.equal(leadUpdate.status,200,'admin should update the commercial pipeline');
 const cost=await fetch(base+'/api/company/costs',{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({description:'Hospedagem de teste',amount:39.9,category:'tecnologia'})});
 assert.equal(cost.status,201,'admin should save an operational cost');
 const companyData=await (await fetch(base+'/api/company',{headers:{cookie}})).json();
 assert.equal(companyData.leads[0].status,'proposal','commercial changes should persist in storage');
 assert.equal(companyData.costs[0].amount,39.9,'cost records should persist in storage');
 const integrationStatus=await fetch(base+'/api/integrations/status',{headers:{cookie}});
 assert.equal(integrationStatus.status,200);
 const programResponse=await fetch(base+'/api/programs',{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({title:'Atividade de teste',source:'Fonte oficial',reward:75,budget:150,url:'https://example.org/task'})});
 assert.equal(programResponse.status,201,'team should create a program');
 const program=await programResponse.json();
 assert.equal(program.status,'pending_funding','new programs must wait for funding review');
 const fundingResponse=await fetch(base+'/api/programs/'+program.id+'/funding',{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({reference:'FUND-TEST-1234',evidenceUrl:'https://example.org/receipt'})});
 assert.equal(fundingResponse.status,200,'admin should review campaign funding evidence');
 const assignmentResponse=await fetch(base+'/api/programs/'+program.id+'/assign',{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({participantId:participant.id})});
 assert.equal(assignmentResponse.status,201,'team should assign the program');
 const assignment=await assignmentResponse.json();
 const participantLogin=await fetch(base+'/api/login',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({email:'participante@example.org',password:'senha-segura-123'})});
 assert.equal(participantLogin.status,200,'approved participant should sign in');
 const participantCookie=participantLogin.headers.get('set-cookie').split(';')[0];
 const participantDash=await (await fetch(base+'/api/dashboard',{headers:{cookie:participantCookie}})).json();
 assert.equal(participantDash.assignments.length,1,'participant should only see their own assigned activity');
 assert.equal(participantDash.assignments[0].id,assignment.id);
 const submitted=await fetch(base+'/api/assignments/'+assignment.id+'/submit',{method:'POST',headers:{cookie:participantCookie,'content-type':'application/json'},body:JSON.stringify({proof:'https://example.org/proof'})});
 assert.equal(submitted.status,200,'participant should submit proof');
 const reviewed=await fetch(base+'/api/assignments/'+assignment.id+'/review',{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({decision:'approved',note:'Comprovante conferido'})});
 assert.equal(reviewed.status,200,'admin should review submitted proof');
 const payment=await fetch(base+'/api/assignments/'+assignment.id+'/payment',{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify({reference:'REF-TEST-1234'})});
 assert.equal(payment.status,200,'admin should record an already completed payment');
 const finalParticipantDash=await (await fetch(base+'/api/dashboard',{headers:{cookie:participantCookie}})).json();
 assert.equal(finalParticipantDash.ledger.length,1,'participant should see their own payment record');
 const referral=await fetch(base+'/api/referrals',{method:'POST',headers:{cookie:participantCookie,'content-type':'application/json'},body:JSON.stringify({email:'indicado@example.org'})});
 assert.equal(referral.status,201,'participant should be able to record a referral');

});
test('opportunity validation rejects unsafe data',()=>{
 assert.equal(validateOpportunity({title:'Trabalho',source:'Fonte',value:10,url:'https://example.org'}).value,10);
 assert.throws(()=>validateOpportunity({title:'x',source:'y',value:1,url:'http://example.org'}),/HTTPS/);
 assert.throws(()=>validateOpportunity({title:'x',source:'y',value:-1}),/valor/i);
 assert.throws(()=>validateOpportunity({title:'x',source:'y',value:'abc'}),/valor/i);
 assert.ok(STATUSES.includes('Recebido'));
 assert.ok(!STATUSES.includes('Pago garantido'));
});
